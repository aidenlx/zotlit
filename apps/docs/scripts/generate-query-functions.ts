// Emits the Functions and methods reference page from the published Query
// Schema of @zotlit/item-query. The descriptions come from the function
// registry; the page framing lives here.
//
// @see docs/adr/0015-template-contract-artifacts-generate-from-ts-types.md

import { writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { format } from "oxfmt";

import schema from "@zotlit/item-query/query.schema.json" with { type: "json" };

import formatConfig from "../oxfmt.config.ts";
import { renderFunctionsReference } from "../src/lib/query-functions/reference.ts";
import type { LanguageVocabulary } from "../src/lib/query-functions/reference.ts";

const packageRoot = resolve(import.meta.dirname, "..");

const PAGE = join(
  packageRoot,
  "content",
  "docs",
  "reference",
  "functions-and-methods.mdx",
);

const FRONTMATTER = `---
title: "Filter Expression functions and methods"
description: "Look up what each function, method, and property returns when you filter papers in a ZotLit Query or match them in a Profile Match."
---`;

const BANNER = `{/* Generated by scripts/generate-query-functions.ts from the @zotlit/item-query Query Schema - DO NOT EDIT. */}
{/* Edit the descriptions in packages/item-query/src/filter-functions.ts, then run \`pnpm exec turbo run generate:query-functions --filter=@zotlit/docs\`. */}`;

const INTRO = `This reference lists every function, method, and property of the [Filter Expression](/docs/concepts/how-zotlit-query-works#steps) language. You write Filter Expressions in the filters and formulas of a [query file](/docs/reference/query-file-format) and in a [Profile Match](/docs/reference/templates/profile-match).

Each signature shows the parameters and the type of the result. A parameter marked \`?\` can be left out, and \`...\` takes any number of arguments. A result can also be null when data is missing.`;

const body = renderFunctionsReference(schema as LanguageVocabulary);

// Formatted as the repo formatter would, so `pnpm format` passes on the page.
const { code, errors } = await format(
  PAGE,
  `${[FRONTMATTER, BANNER, INTRO, body].join("\n\n")}\n`,
  formatConfig,
);
if (errors.length > 0)
  throw new AggregateError(errors, `Cannot format ${PAGE}`);
await writeFile(PAGE, code);

console.log(
  `Functions and methods page: ${schema.functions.length} functions, ${schema.methods.length} methods, ${schema.properties.length} properties.`,
);
