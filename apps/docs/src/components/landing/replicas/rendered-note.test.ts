// The landing's literature-note and Workbench replicas print what ZotLit's
// real renderer writes for Sandve et al. 2013 under the Default profile. The
// page cannot carry the renderer, so `rendered-note.ts` holds its output; this
// test renders it again and fails when the Default profile or the renderer
// changes what a note looks like.
//
// The paper is the Workbench's own sample journal article re-dressed with
// Sandve et al.'s real metadata from the docs Fixture
// (packages/scripts/lib/fixture/spec.ts, `DOCS_ITEMS`).

import { writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

import {
  DEFAULT_PROFILE_SOURCE,
  SAMPLE_ITEMS,
  renderProfile,
} from "@zotlit/workbench/render";
import type { ItemSnapshot } from "@zotlit/workbench/snapshot";

import { RENDERED_NOTE } from "./rendered-note";

const creators = [
  ["Geir Kjetil", "Sandve"],
  ["Anton", "Nekrutenko"],
  ["James", "Taylor"],
  ["Eivind", "Hovig"],
].map(([given, family]) => ({
  family,
  given,
  literal: null,
  role: "author",
  fullName: `${given} ${family}`,
}));

const date = {
  kind: "text",
  value: null,
  text: "2013",
  year: 2013,
  month: null,
  day: null,
  raw: "2013",
};

const OVERRIDES: Record<string, unknown> = {
  title: "Ten Simple Rules for Reproducible Computational Research",
  date,
  citationKey: "sandve2013",
  citekey: "sandve2013",
  publicationTitle: "PLOS Computational Biology",
  containerTitle: "PLOS Computational Biology",
  key: "DCSNDART",
  indexedKey: "DCSNDART",
  volume: "9",
  issue: "10",
  pages: "e1003285",
  creators,
  authors: creators,
  authorsShort: "Sandve et al.",
  backlink: "zotero://select/library/items/DCSNDART",
  librarylink: "obsidian://zotlit/show-in-library?item-key=DCSNDART",
  collections: [
    { key: "DCRPRDCB", name: "Reproducibility", path: ["Reproducibility"] },
  ],
};

/** Replaces each named field wherever it sits in the snapshot's template roots. */
function dress(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(dress);
  if (value === null || typeof value !== "object") return value;
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(value)) {
    out[k] = k in OVERRIDES && k !== "key" ? OVERRIDES[k] : dress(v);
  }
  if ("key" in out && out["key"] === "IANNP5A2") out["key"] = "DCSNDART";
  if ("indexedKey" in out && out["indexedKey"] === "IANNP5A2")
    out["indexedKey"] = "DCSNDART";
  return out;
}

const journalArticle = SAMPLE_ITEMS[0]!;

const SANDVE_SNAPSHOT = {
  ...journalArticle,
  item: {
    ...journalArticle.item,
    key: "DCSNDART",
    indexedKey: "DCSNDART",
    title: OVERRIDES["title"],
  },
  roots: dress(journalArticle.roots),
} as unknown as ItemSnapshot;

describe("the landing's rendered literature note", () => {
  it("is what the Default profile renders for Sandve et al. 2013", () => {
    const result = renderProfile(DEFAULT_PROFILE_SOURCE, SANDVE_SNAPSHOT);
    expect(result.diagnostics).toEqual([]);
    const rendered = {
      source: DEFAULT_PROFILE_SOURCE,
      filename: result.filename,
      frontmatter: result.frontmatterBlock,
      properties: result.properties,
      body: result.creationBody,
    };
    // `UPDATE_LANDING_NOTE=1 pnpm exec vitest run <this file>` rewrites the data file.
    if (process.env["UPDATE_LANDING_NOTE"]) {
      writeFileSync(
        new URL("rendered-note.ts", import.meta.url),
        `// Generated by rendered-note.test.ts (UPDATE_LANDING_NOTE=1): the Default\n// profile and what ZotLit renders from it for Sandve et al. 2013.\n\nexport const RENDERED_NOTE = ${JSON.stringify(rendered, null, 2)};\n`,
      );
    }
    expect(rendered).toEqual(RENDERED_NOTE);
  });
});
